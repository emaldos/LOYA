const fs=require("fs")
const path=require("path")
const ROOT=path.resolve(__dirname,"..","..")
const source=fs.readFileSync(path.join(ROOT,"UI","js","components","ext-agents.js"),"utf8")
const start=source.indexOf("// ---- ext pure start")
const end=source.indexOf("// ---- ext pure end")
if(start<0||end<start)throw new Error("could not find the pure helpers in ext-agents.js")
const api=new Function(source.slice(start,end)+"\nreturn {EXT_AGENT_KINDS,extIsAgentKind,extProviderOf,extSkillMatches,extMergeSlashRows,extFindSkill,extBannerText,extStatusPill}")()
const aiSource=fs.readFileSync(path.join(ROOT,"UI","js","components","ai.js"),"utf8")
const ai=new Function(aiSource.slice(aiSource.indexOf("const AI_SLASH_COMMANDS"),aiSource.indexOf("function aiEscapeHtml"))+"\nreturn {AI_SLASH_COMMANDS,aiChainMatches,aiSlashMatches,aiParseSlash}")()
let passed=0,failed=0
function check(name,cond,detail){if(cond){passed++;return}failed++;console.log("  FAIL  "+name+(detail?"  ->  "+detail:""))}
function eq(name,a,b){check(name,JSON.stringify(a)===JSON.stringify(b),JSON.stringify(a)+" != "+JSON.stringify(b))}
// provider selector
eq("agent kinds",[api.extIsAgentKind("ext:claude"),api.extIsAgentKind("ext:codex"),api.extIsAgentKind("api"),api.extIsAgentKind("")],[true,true,false,false])
eq("provider of",[api.extProviderOf("ext:codex"),api.extProviderOf("ollama")],["codex",""])
check("no Claude Code branding anywhere",!/Claude Code/.test(source.replace(/claude-agent-sdk/g,"")))
// "/" popup merge
const skills=[{name:"recon-sum",description:"Summarise recon",source:"personal (~/.claude/skills)",kind:"skill",provider:"claude"},{name:"compact",source:"reported by Claude Agent",kind:"command",provider:"claude"},{name:"help",source:"project",kind:"skill",provider:"claude"},{name:"nmap-chain",source:"project",kind:"skill",provider:"claude"}]
const rows=api.extSkillMatches(skills,"",["help","/nmap-chain"])
eq("built-ins and chains win name clashes",rows.map((r)=>r.label),["/recon-sum","/compact"])
check("rows say where they come from",rows[0].detail.includes("Claude Agent skill · personal (~/.claude/skills)"),rows[0].detail)
check("commands labelled as commands",rows[1].detail.startsWith("Claude Agent command"),rows[1].detail)
eq("prefix match first",api.extSkillMatches(skills,"rec",[]).map((r)=>r.name),["recon-sum"])
eq("description match",api.extSkillMatches(skills,"summarise",[]).map((r)=>r.name),["recon-sum"])
eq("agent-skill kind",rows[0].kind,"agent-skill")
const builtin=ai.aiSlashMatches("").map((c)=>({kind:"slash",label:"/"+c.name}))
const chains=ai.aiChainMatches([{caller:"webrecon",name:"Web recon",steps:3},{caller:"help",steps:1}],"")
const merged=api.extMergeSlashRows(builtin,chains,api.extSkillMatches(skills.concat([{name:"webrecon",kind:"skill",provider:"claude"}]),"",[]))
eq("merged order: LOYA commands, chains, agent skills",merged.slice(builtin.length).map((r)=>r.label),["/webrecon","/recon-sum","/compact","/nmap-chain"])
check("merged has no duplicate labels",new Set(merged.map((r)=>r.label.toLowerCase())).size===merged.length)
eq("find skill case-insensitive",api.extFindSkill(skills,"RECON-SUM").name,"recon-sum")
eq("find skill missing",api.extFindSkill(skills,"nope"),null)
eq("unknown slash still parses for agent dispatch",[ai.aiParseSlash("/recon-sum 10.0.0.0/24").command,ai.aiParseSlash("/recon-sum 10.0.0.0/24").arg],[null,"10.0.0.0/24"])
const loya=api.extSkillMatches([{name:"loya-recon",description:"Recon with approval",source:"LOYA skill",kind:"skill",provider:"codex"}],"loya",[])
check("bundled skills are labelled LOYA skill",loya[0].detail.startsWith("LOYA skill · for OpenAI Codex"),loya[0].detail)
// banner and status
eq("banner",api.extBannerText("ext:claude","read: 9 areas · delete: off"),"Data is sent to Anthropic (Claude Agent) · permissions: read: 9 areas · delete: off")
eq("banner codex",api.extBannerText("ext:codex","x"),"Data is sent to OpenAI (OpenAI Codex) · permissions: x")
eq("no banner for LOYA AI",api.extBannerText("api","x"),"")
eq("pill not installed",api.extStatusPill({installed:false}).text,"Not installed")
eq("pill ready",api.extStatusPill({installed:true,ready:true}).text,"Ready")
eq("pill reconsent",api.extStatusPill({installed:true,ready:false,reason:"reconsent_required"}),{text:"Needs consent",cls:"offline"})
eq("pill no key",api.extStatusPill({installed:true,reason:"no_key"}).text,"No key")
// ai.js wiring
check("ai.js routes agent turns to extAgents.run_start",aiSource.includes('agent?"extAgents.run_start":"ai.chat_send_stream_start"'))
check("ai.js Stop kills the agent process",aiSource.includes('bridgeCall("extAgents.stop",[aiState.activeStreamId])'))
check("ai.js approval shows the agent's reason",aiSource.includes("The agent's stated reason"))
check("settings never echoes a stored key back",!/ext-key"[^>]*value=/.test(source))
console.log(`ext_agents: ${passed} passed, ${failed} failed`)
if(failed)process.exit(1)
