const fs=require("fs")
const path=require("path")
const ROOT=path.resolve(__dirname,"..","..")
const source=fs.readFileSync(path.join(ROOT,"UI","js","components","ai.js"),"utf8")
const start=source.indexOf("const AI_SLASH_COMMANDS")
const end=source.indexOf("function aiEscapeHtml")
if(start<0||end<start)throw new Error("could not find the pure helpers in ai.js")
const api=new Function(source.slice(start,end)+"\nreturn {AI_SLASH_COMMANDS,aiChainMatches,aiChainStepCount,aiParseSlash,aiSlashMatches,aiActiveToken,aiApplyCompletion,aiExtractCommand,aiHistoryStep,aiSlashHelpText}")()
let passed=0,failed=0
function check(name,cond,detail){if(cond){passed++;return}failed++;console.log("  FAIL  "+name+(detail?"  ->  "+detail:""))}
function eq(name,a,b){check(name,JSON.stringify(a)===JSON.stringify(b),JSON.stringify(a)+" != "+JSON.stringify(b))}
const p=api.aiParseSlash("/explain  nmap -sV {IPv4} ")
eq("parse name+arg",[p.name,p.arg,!!p.command],["explain","nmap -sV {IPv4}",true])
eq("parse no arg",api.aiParseSlash("/help").arg,"")
eq("parse unknown keeps name",[api.aiParseSlash("/nope x").name,api.aiParseSlash("/nope x").command],["nope",null])
eq("parse multiline arg",api.aiParseSlash("/new-note a\nb").arg,"a\nb")
eq("not a slash",api.aiParseSlash("explain /x"),null)
eq("plain path is not a command",api.aiParseSlash("/etc/passwd"),null)
eq("matches prefix first",api.aiSlashMatches("s").map((c)=>c.name).slice(0,3),["summarize-note","suggest-next","search"])
eq("matches all on empty",api.aiSlashMatches("").length,api.AI_SLASH_COMMANDS.length)
check("matches by description",api.aiSlashMatches("terminal").some((c)=>c.name==="run"))
eq("every command has a description",api.AI_SLASH_COMMANDS.filter((c)=>!c.desc).length,0)
eq("help lists every command",api.AI_SLASH_COMMANDS.every((c)=>api.aiSlashHelpText().includes("/"+c.name)),true)
eq("token slash",api.aiActiveToken("/ex",3),{type:"slash",query:"ex",start:0,end:3})
eq("token slash caret mid",api.aiActiveToken("/explain",2),{type:"slash",query:"e",start:0,end:8})
eq("token mention",api.aiActiveToken("look at @nm",11),{type:"mention",query:"nm",start:8,end:11})
eq("token bare @",api.aiActiveToken("@",1),{type:"mention",query:"",start:0,end:1})
eq("email-like is not a mention",api.aiActiveToken("mail a@b.io",11),null)
const arg=api.aiActiveToken("/run nmap -s",12)
eq("token arg",[arg.type,arg.query,arg.start,arg.kinds],["arg","nmap -s",5,["command"]])
eq("no arg completion for free-text commands",api.aiActiveToken("/new-note recon checklist",25),null)
eq("token word",api.aiActiveToken("how to use nma",14),{type:"word",query:"nma",start:11,end:14})
eq("short word ignored",api.aiActiveToken("hi nm",5),null)
eq("caret inside a word gives nothing",api.aiActiveToken("nmapx",3),null)
eq("apply slash",api.aiApplyCompletion("/ex",{start:0,end:3},"/explain"),{text:"/explain ",caret:9})
eq("apply mention removes token",api.aiApplyCompletion("look at @nm",{start:8,end:11},""),{text:"look at ",caret:8})
eq("apply mention mid text",api.aiApplyCompletion("see @nm please",{start:4,end:7},""),{text:"see please",caret:4})
eq("apply mention alone",api.aiApplyCompletion("@nm",{start:0,end:3},""),{text:"",caret:0})
eq("apply word keeps following space",api.aiApplyCompletion("use nma now",{start:4,end:7},"Nmap"),{text:"use Nmap now",caret:8})
eq("extract fenced",api.aiExtractCommand("Reason.\n```bash\n# scan\n$ nmap -sV 10.0.0.1\n```"),"nmap -sV 10.0.0.1")
eq("extract none",api.aiExtractCommand("no code here"),"")
const chains=[{caller:"webrecon",name:"Web recon",steps:[1,2,3]},{caller:"fullscan",name:"Full scan",steps:1,description:"nmap then web"},{caller:"help",name:"clash",steps:2},{caller:"",name:"broken"}]
eq("chains list on empty query, built-ins and blanks dropped",api.aiChainMatches(chains,"").map((r)=>r.label),["/webrecon","/fullscan"])
eq("chain row shape",api.aiChainMatches(chains,"web")[0],{kind:"chain",label:"/webrecon",detail:"Action chain · 3 steps - Web recon",caller:"webrecon"})
eq("chain matched by description after callers",api.aiChainMatches(chains,"web").map((r)=>r.caller),["webrecon","fullscan"])
eq("singular step",api.aiChainMatches(chains,"full")[0].detail,"Action chain · 1 step - Full scan")
eq("chain caller parses as a slash name",[api.aiParseSlash("/web_recon2").name,api.aiParseSlash("/web_recon2").command],["web_recon2",null])
eq("no chains",api.aiChainMatches(undefined,"x"),[])
const h=["a","b","c"]
eq("history up from fresh",api.aiHistoryStep(h,-1,-1),{index:2,text:"c"})
eq("history up again",api.aiHistoryStep(h,2,-1),{index:1,text:"b"})
eq("history up stops at oldest",api.aiHistoryStep(h,0,-1),{index:0,text:"a"})
eq("history down past newest clears",api.aiHistoryStep(h,2,1),{index:-1,text:""})
eq("history down when not browsing",api.aiHistoryStep(h,-1,1),{index:-1,text:null})
eq("history empty",api.aiHistoryStep([],-1,-1),{index:-1,text:null})
// aiRunChain: the chat notice must follow the outcome, not claim "Running" before the confirmation.
const runSrc=source.slice(source.indexOf("function aiRunChain("),source.indexOf("const AI_LEVEL_LABELS"))
function runChainWith(result){
const notices=[]
const fn=new Function("aiNotice","loyaRunChainByCaller","showStatusIsland",runSrc+"\nreturn aiRunChain")((t)=>notices.push(t),()=>Promise.resolve(result),()=>{})
fn("demo")
return new Promise((r)=>setTimeout(()=>r(notices),0))
}
const runChecks=Promise.all([runChainWith({started:true}),runChainWith({started:false,reason:"cancelled"}),runChainWith({started:false,reason:"unknown-caller"})]).then(([ok,cancelled,unknown])=>{
eq("ai /caller started -> running notice",ok,["Running action chain /demo - progress shows in the chain runner."])
eq("ai /caller cancelled -> not-run notice",cancelled,["Action chain /demo was not run."])
eq("ai /caller unknown -> no chat notice (toast already says so)",unknown,[])
})
runChecks.then(()=>{
console.log("\n"+passed+" passed, "+failed+" failed")
process.exit(failed?1:0)
})
