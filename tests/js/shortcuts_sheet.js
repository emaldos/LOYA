const fs=require("fs")
const path=require("path")
const src=fs.readFileSync(path.join(__dirname,"..","..","UI","js","components","shortcuts.js"),"utf8")
const a=src.indexOf("function shortcutSheetColumns"),b=src.indexOf("function openShortcutsSheet")
const m=new Function(src.slice(a,b)+";return {shortcutSheetColumns,shortcutSheetFilter}")()
let passed=0,failed=0
function check(name,ok,detail){if(ok)passed++;else{failed++;console.log("FAIL: "+name+(detail?" - "+detail:""))}}
const mk=(n,c)=>({scope:n,items:Array.from({length:c},(_,i)=>({keys:"Ctrl+"+i,desc:n+" thing "+i}))})
const count=(cols)=>cols.flat().reduce((n,s)=>n+s.items.length,0)
const weight=(col)=>col.reduce((n,s)=>n+1.5+s.items.length,0)
const sheet=[mk("Global",3),mk("Dashboard",3),mk("Note editor",3),mk("Terminal",21)]
const cols=m.shortcutSheetColumns(sheet)
check("two columns",cols.length===2)
check("no row lost or duplicated",count(cols)===30)
check("columns are balanced",Math.abs(weight(cols[0])-weight(cols[1]))<=3,JSON.stringify(cols.map(weight)))
check("a split section is marked continued",cols[1][0].scope==="Terminal"&&cols[1][0].cont===true)
check("no split leaves fewer than two rows",cols.flat().every((s)=>s.items.length>=2))
check("order is preserved",cols.flat().map((s)=>s.items).flat().map((r)=>r.desc).join()===sheet.map((s)=>s.items).flat().map((r)=>r.desc).join())
check("one small section stays in one column",m.shortcutSheetColumns([mk("A",2)]).length===1)
check("empty input gives no columns",m.shortcutSheetColumns([]).length===0)
check("small sections are not split",m.shortcutSheetColumns([mk("A",3),mk("B",3)]).flat().every((s)=>!s.cont))
check("filter matches description and keys, all words",count([m.shortcutSheetFilter(sheet,"terminal ctrl+2")])===2)
check("filter is case-insensitive",count([m.shortcutSheetFilter(sheet,"GLOBAL")])===3)
check("filter drops empty sections",m.shortcutSheetFilter(sheet,"dashboard").length===1)
check("no match gives nothing",m.shortcutSheetFilter(sheet,"zzz").length===0)
check("blank query keeps everything",m.shortcutSheetFilter(sheet,"   ")===sheet)
const pal=fs.readFileSync(path.join(__dirname,"..","..","UI","js","components","palette.js"),"utf8")
check("palette empty state does not point at actions that are not shown",pal.indexOf("pick an action above")<0&&pal.indexOf("Type to search notes, commands, targets and actions")>=0)
const term=fs.readFileSync(path.join(__dirname,"..","..","UI","js","components","terminal.js"),"utf8")
check("terminal maximize key is bound and listed",term.indexOf('e.ctrlKey&&e.shiftKey&&!e.altKey&&e.key==="Enter"')>=0&&/\{keys:"Ctrl\+Shift\+Enter",desc:"Maximize or restore the terminal panel"\}/.test(src))
console.log(passed+" passed, "+failed+" failed")
process.exit(failed?1:0)
