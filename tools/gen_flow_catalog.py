#!/usr/bin/env python3
"""Write UI/js/components/flow-catalog.js from Cores/Services/flow_nodes.py (the node catalog the canvas, the inspector and
the JS validator read). Run it after every change to flow_nodes.SPECS / CATEGORIES / PRESETS / HOTBAR:

    python tools/gen_flow_catalog.py          # rewrite the file
    python tools/gen_flow_catalog.py --check  # exit 1 when the file is stale (tests/test_flow_nodes.py does the same)

The output is deterministic: one JSON line, keys in declaration order, ASCII only, LF line endings."""
import json,os,sys
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:sys.path.insert(0,ROOT)
OUTPUT=os.path.join(ROOT,"UI","js","components","flow-catalog.js")
HEADER="// GENERATED by tools/gen_flow_catalog.py from Cores/Services/flow_nodes.py - do not edit by hand.\n"
FOOTER='if(typeof module!=="undefined"&&module.exports)module.exports={FLOW_CATALOG}\n'
def render():
    from Cores.Services import flow_nodes,flow_schema
    data=flow_nodes.flow_catalog(flow_schema.SCHEMA_VERSION)
    return HEADER+"const FLOW_CATALOG="+json.dumps(data,sort_keys=False,ensure_ascii=True,indent=None,separators=(",",":"))+"\n"+FOOTER
def current():
    try:
        with open(OUTPUT,"r",encoding="utf-8",newline="") as handle:return handle.read()
    except OSError:return None
def main(argv=None):
    argv=sys.argv[1:] if argv is None else argv
    text=render()
    if "--check" in argv:
        if current()==text:return 0
        sys.stderr.write("UI/js/components/flow-catalog.js is stale: run python tools/gen_flow_catalog.py\n")
        return 1
    if current()!=text:
        with open(OUTPUT,"w",encoding="utf-8",newline="\n") as handle:handle.write(text)
        print("wrote "+os.path.relpath(OUTPUT,ROOT))
    else:print("up to date: "+os.path.relpath(OUTPUT,ROOT))
    return 0
if __name__=="__main__":
    sys.exit(main())
