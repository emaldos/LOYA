    @server.tool(description="Run an Action Chain by id: its steps run one after another in the background, stopping at the first failure, with {Placeholders} filled from the live target. Refuses if a step still has an unfilled placeholder. Poll chains_status with the returned chain_id.")
    def chains_run(chain_id: int) -> dict:
        _lock_check()
        if _ai_svc.tool_decision("chains_run")=="deny":_check("chains_run",locals())
        from Cores.Services import playbooks_service as _chains_svc
        from Cores.Services import flow_store as _flow_store
        if _flow_store.has_graph(chain_id):return _run_chain_diagram(chain_id,"")  # a chain with a diagram runs through the flow engine
        steps=_chains_svc.playbook_commands(chain_id)
        if not steps:raise ValueError("No such Action Chain, or it has no steps.")
        rep=_live_resolver();items=[]
        for n,step in enumerate(steps,1):
            cmd=rep.apply(step["command"])
            missing=_missing_placeholders(cmd)
            if missing:raise ValueError(f"Step {n} ({step['label']}) needs values the live target does not have: "+", ".join("{"+m+"}" for m in missing))
            items.append({"command":cmd,"label":step["label"]})
        destructive=any(_terminal_svc.command_is_destructive(i["command"]) for i in items)
        _check("chains_run",{"chain_id":chain_id,"steps":[i["command"] for i in items]},force_ask=destructive)
        book=_chains_svc.get_playbook(chain_id) or {}
        return _terminal_svc.start_chain("",items,"stop","ai",str(book.get("name") or ""))
