    # Chain Diagrams: an Action Chain drawn as a graph (commands, scripts, decisions, loops). AI Roles entity "Chain Diagrams".
    def _run_chain_diagram(chain_id,reason):
        # One gate for chain_run and for chains_run on a chain that has a diagram. Deny always denies. A chain the operator has
        # not reviewed yet (AI-made or imported), a destructive command, a script node or an HTTP / file node sends the call to the operator's
        # approval queue whatever the level or session grants say (force_ask).
        _lock_check()
        from Cores.Services import flow_service as _flow_svc
        if _ai_svc.tool_decision("chain_run")=="deny":_check("chain_run",{"chain_id":chain_id})
        info=_flow_svc.ai_run_info(chain_id)
        _check("chain_run",{"chain_id":chain_id,"name":info["name"],"reason":reason,"first_run_of_unreviewed_chain":info["unreviewed"],"scripts":info["scripts"],"sub_chains":info["subchains"],"destructive":info["destructive"],"commands":info["commands"],"actions":info["actions"]},force_ask=info["force_ask"])
        return _flow_svc.ai_run(chain_id,info["fingerprint"],approved_first_run=info["unreviewed"],operator_approved=info["force_ask"])  # refused if the diagram changed meanwhile
