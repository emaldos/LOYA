    @server.tool(description="List Quick Run commands (the operator's saved commands) with {Placeholders} filled in from the live target. 'missing' lists placeholders the live target has no value for. Optional query filters by title, category or command text.")
    def quickrun_list(query: str="") -> list:
        _check("quickrun_list",locals())
        from Cores.Services import search_service as _search_svc
        _dbp,rows=_search_svc._load_cmds()
        from Cores.Bridge import mcp_app_tools as _app_tools
        rep=_app_tools.masked_resolver();q=(query or "").strip().lower();out=[]  # secret placeholders stay masked
        for r in rows:
            cmd=str(r.get("command") or "").strip()
            if not cmd:continue
            title=str(r.get("title") or r.get("cmd_note_title") or "")
            if q and q not in (title+" "+str(r.get("category",""))+" "+cmd).lower():continue
            resolved=rep.apply(cmd)
            out.append({"id":r.get("id"),"source":r.get("src") or r.get("db") or "","title":title,"category":r.get("category",""),"command":cmd,"resolved":resolved,"missing":_missing_placeholders(resolved)})
            if len(out)>=100:break
        return out
    @server.tool(description="Ask to run one Quick Run command (by the id from quickrun_list) with the live target's values filled in. Like terminal_run it only queues the command - a human approves it in the app unless automatic approval is on. Fails if a placeholder has no value yet.")
    def quickrun_run(command_id: int,reason: str="") -> dict:
        _lock_check()
        if _ai_svc.tool_decision("quickrun_run")=="deny":_check("quickrun_run",locals())
        from Cores.Services import search_service as _search_svc
        _dbp,rows=_search_svc._load_cmds()
        row=next((r for r in rows if str(r.get("id"))==str(command_id)),None)
        if row is None:raise ValueError("No such Quick Run command.")
        from Cores.Bridge import mcp_app_tools as _app_tools
        raw=str(row.get("command") or "")
        resolved=_live_resolver().apply(raw)
        shown=_app_tools.masked_resolver().apply(raw)  # what the AI and the audit summary see
        missing=_missing_placeholders(resolved)
        if missing:raise ValueError("Fill these in on the live target first: "+", ".join("{"+m+"}" for m in missing))
        level=_check("quickrun_run",{"command_id":command_id,"command":shown,"reason":reason},defer_ask=True)
        # The real values go only into the queued command, which the operator sees and approves in the app.
        out=_terminal_svc.request_ai_command(resolved,"",reason or ("Quick Run: "+str(row.get("title") or "")),"ask" if level=="ask" else _ai_svc.terminal_approval_mode())
        if isinstance(out,dict) and out.get("command")==resolved:out=dict(out,command=shown)
        return out
