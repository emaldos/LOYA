"""Bridge module api.reports - report model, sections, findings, templates, library (see the reporting contract)."""
from Cores.Services import reports_service as _svc
from Cores.Services import report_schedule as _schedule
class ReportsAPI:
    def __init__(self):self._window=None
    def bind(self,window):self._window=window
    def list(self):return _svc.list_reports()
    def get(self,report_id):return _svc.get_report(report_id)
    def create(self,payload=None):return _svc.create_report(payload)
    def update(self,report_id,patch):return _svc.update_report(report_id,patch)
    def duplicate(self,report_id):return _svc.duplicate_report(report_id)
    def delete(self,report_id):return _svc.delete_report(report_id)
    def section_add(self,report_id,fields=None):return _svc.add_section(report_id,fields)
    def section_update(self,section_id,patch):return _svc.update_section(section_id,patch)
    def section_delete(self,section_id):return _svc.delete_section(section_id)
    def sections_reorder(self,report_id,ids):return _svc.reorder_sections(report_id,ids)
    def section_boilerplate(self,kind,report_id=None):return _svc.section_boilerplate(kind,report_id)
    def schedule_get(self,report_id):return _svc.get_report(report_id)["meta"].get("schedule") or {"milestones":[]}
    def schedule_set(self,report_id,schedule):
        _svc.update_report(report_id,{"meta":{"schedule":_schedule.normalize(schedule)}})
        return self.schedule_get(report_id)
    def reminders_due(self):return _schedule.due_reminders(None,"app")
    def upcoming(self,limit=20):return _schedule.upcoming(limit)
    def deadlines(self):return _schedule.deadlines()
    def finding_add(self,report_id,fields=None):return _svc.add_finding(report_id,fields)
    def finding_get(self,finding_id):return _svc.get_finding(finding_id)
    def finding_update(self,finding_id,patch):return _svc.update_finding(finding_id,patch)
    def finding_delete(self,finding_id):return _svc.delete_finding(finding_id)
    def findings_reorder(self,report_id,ids):return _svc.reorder_findings(report_id,ids)
    def findings_sort(self,report_id,by="severity"):return _svc.sort_findings(report_id,by)
    def library_list(self):return _svc.library_list()
    def library_get(self,library_id):return _svc.library_get(library_id)
    def library_save(self,entry):return _svc.library_save(entry)
    def library_save_from_finding(self,finding_id,category=""):return _svc.library_save_from_finding(finding_id,category)
    def library_delete(self,library_id):return _svc.library_delete(library_id)
    def finding_from_library(self,report_id,library_id):return _svc.finding_from_library(report_id,library_id)
    def templates(self):return _svc.templates()
    def template_get(self,template_id):return _svc.template_get(template_id)
    def template_save_from_report(self,report_id,name,description=""):return _svc.template_save_from_report(report_id,name,description)
    def template_save(self,template):return _svc.template_save(template)
    def template_delete(self,template_id):return _svc.template_delete(template_id)
    def placeholders(self):return _svc.placeholders()
    def versions(self,report_id):return _svc.versions(report_id)
    def version_create(self,report_id,label=""):return _svc.version_create(report_id,label)
    def version_restore(self,report_id,version_id):return _svc.version_restore(report_id,version_id)
    def version_delete(self,version_id):return _svc.version_delete(version_id)
    def cvss_calc(self,vector):return _svc.cvss_calc(vector)
    def sanitize(self,text):return _svc.sanitize_html(text)
    def asset_add(self,name,data_b64):return _svc.asset_add(name,data_b64)
    def asset_get(self,uid):return _svc.asset_get(uid)
    def sources(self,profile_id=None):return _svc.sources(profile_id)
    # Report scope from Targets (optional): links keep a snapshot; secret values only after target_allow_secret.
    def targets_available(self,query=None):return _svc.targets_available(query)
    def targets_list(self,report_id):return _svc.targets_list(report_id)
    def target_link(self,report_id,items):return _svc.target_link(report_id,items)
    def target_unlink(self,report_id,uid):return _svc.target_unlink(report_id,uid)
    def target_update(self,report_id,uid=None):return _svc.target_update(report_id,uid)
    def target_allow_secret(self,report_id,uid,key,allow=True):return _svc.target_allow_secret(report_id,uid,key,allow)
    def targets_reorder(self,report_id,uids):return _svc.targets_reorder(report_id,uids)
    def targets_state(self,report_id):return _svc.targets_state(report_id)
    def targets_restore(self,report_id,state):return _svc.targets_restore(report_id,state)
    def finding_targets_set(self,finding_id,targets):return _svc.finding_targets_set(finding_id,targets)
    def note_content(self,note_id):return _svc.note_content(note_id)
    def note_findings(self,note_ids):return _svc.note_findings(note_ids)
    def defaults_get(self):return _svc.defaults_get()
    def defaults_set(self,patch):return _svc.defaults_set(patch)
    def stats(self):return _svc.stats()
